"""Typed operating observations and reproducible direct-cost economics.

No actuals are generated by this module. Templates/assumptions remain separate;
records validate evidence structure and scope, not a human, invoice or interview.
"""
from __future__ import annotations

from datetime import date, datetime, timedelta, timezone
from decimal import Decimal, InvalidOperation, localcontext
import re

from .attestations import validate_attestation
from .identities import digest, instant
from .lifecycle import implementation_hash
from .receipts import get_receipt, list_receipts, put_receipt, transaction

VERSION = "omni-operating-observation-1"
KINDS = {"cost", "run_cost", "review_effort", "useful_brief", "customer_feedback", "cost_completeness", "useful_event_census"}
CATEGORIES = {"reviewer_labor", "operator_labor", "vendor", "compute_storage", "other"}


def decimal_amount(value, *, signed=False):
    pattern = (r"-?" if signed else "") + r"(?:0|[1-9]\d{0,14})(?:\.\d{1,6})?"
    if not isinstance(value,str) or not re.fullmatch(pattern,value):
        raise ValueError("exact decimal string required" if signed else "exact nonnegative decimal string required")
    try:
        result=Decimal(value)
    except InvalidOperation as exc:
        raise ValueError("invalid decimal amount") from exc
    if not result.is_finite(): raise ValueError("finite monetary amount required")
    return result


def cost_components(record):
    """Workbook-compatible measured costs; no default rates or blank-as-zero.

    A run row is one allocation, with all seven numeric inputs and an exact
    reference. Vendor/storage/other credits may be signed; labor inputs may not.
    Calculations use 40 decimal digits, without an invented currency rounding
    policy. Separate clock observations remain the source of elapsed effort.
    """
    if record.get("kind")=="cost":
        category=record.get("category")
        if category not in CATEGORIES: raise ValueError("unsupported cost category")
        return {category:decimal_amount(record.get("amount"),signed=category in {"vendor","compute_storage","other"})}
    if record.get("kind")!="run_cost": raise ValueError("cost or run_cost observation required")
    with localcontext() as context:
        context.prec=40
        return {
            "reviewer_labor":decimal_amount(record.get("review_minutes"))*decimal_amount(record.get("review_hourly_rate"))/Decimal(60),
            "operator_labor":decimal_amount(record.get("operator_minutes"))*decimal_amount(record.get("operator_hourly_rate"))/Decimal(60),
            "vendor":decimal_amount(record.get("vendor_amount"),signed=True),
            "compute_storage":decimal_amount(record.get("compute_storage_amount"),signed=True),
            "other":decimal_amount(record.get("other_amount"),signed=True),
        }


def _run_window(record, start, end):
    if bool(record.get("incurred_at"))==bool(record.get("incurred_date")):
        raise ValueError("run cost requires exactly one incurred timestamp or calendar date")
    if record.get("incurred_at"):
        if not start<=instant(record["incurred_at"])<end:
            raise ValueError("run cost incurred outside reporting window")
    else:
        value=record["incurred_date"]
        if record.get("cost_timezone")!="UTC" or not isinstance(value,str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}",value):
            raise ValueError("calendar cost dates require an explicit UTC calendar contract")
        day=datetime.combine(date.fromisoformat(value),datetime.min.time(),timezone.utc)
        if not start<=day or not day+timedelta(days=1)<=end:
            raise ValueError("date-only cost requires the entire calendar day in the reporting window")


def _references(record):
    refs=list(record.get("source_refs",[]))
    for key in ("attestation_ref","brief_ref","consent_ref"):
        if record.get(key): refs.append(record[key])
    for key in ("cost_refs","assessment_refs"):
        refs.extend(record.get(key,[]))
    if any(not isinstance(x,str) or not x for x in refs):
        raise ValueError("operating receipt references must be exact identifiers")
    return sorted(set(refs))


def _shape(record):
    if record.get("contract")!=VERSION or record.get("kind") not in KINDS:
        raise ValueError("unsupported operating contract/kind")
    for key in ("observation_id","scope_hash","implementation_hash","policy_hash"):
        if not isinstance(record.get(key),str) or not record[key] or len(record[key])>250:
            raise ValueError("operating identity/scope/version missing: "+key)
    start,end,observed=map(instant,(record.get("window_start"),record.get("window_end"),record.get("observed_at")))
    if not start<end<=observed:
        raise ValueError("operating reporting window must be closed before observation")
    evidence=record.get("evidence_kind")
    if evidence not in {"operator_evidence","synthetic","assumption","template"}:
        raise ValueError("operating evidence kind required")
    if evidence in {"template","assumption"}:
        return record
    external=record.get("external_reference")
    if (not isinstance(external,dict) or not isinstance(external.get("reference"),str)
            or not external["reference"].strip() or not re.fullmatch(r"[a-f0-9]{64}",str(external.get("sha256","")))):
        raise ValueError("exact external operating evidence reference/hash required")
    if not isinstance(record.get("source_refs",[]),list): raise ValueError("source references must be a list")
    kind=record["kind"]
    if kind in {"cost","run_cost"}:
        cost_components(record)
        if not re.fullmatch(r"[A-Z]{3}",str(record.get("currency",""))):
            raise ValueError("cost category/currency missing")
        if not isinstance(record.get("allocation_basis"),str) or not record["allocation_basis"].strip():
            raise ValueError("explicit allocation basis required")
        if kind=="run_cost":
            if not isinstance(record.get("run_id"),str) or not record["run_id"].strip():
                raise ValueError("stable run/allocation ID required")
            _run_window(record,start,end)
    elif kind=="review_effort":
        a,b=instant(record.get("started_at")),instant(record.get("ended_at"))
        elapsed=(b-a).total_seconds()
        if not start<=a<b<=end or record.get("role") not in {"reviewer","operator"} or not (record.get("event_id") or record.get("run_id")):
            raise ValueError("review effort scope/time/role invalid")
        if record.get("elapsed_seconds")!=elapsed:
            raise ValueError("elapsed seconds must equal the evidenced clock difference")
    elif kind=="useful_brief":
        if type(record.get("useful")) not in {bool,type(None)} or not isinstance(record.get("event_ids"),list):
            raise ValueError("explicit useful/negative/unknown assessment and event IDs required")
        if not record.get("brief_ref") or len(record["event_ids"])!=len(set(record["event_ids"])):
            raise ValueError("reviewed brief reference/unique event IDs required")
        if not start<=instant(record.get("assessed_at"))<end:
            raise ValueError("explicit useful assessment time must lie inside reporting window")
    elif kind=="customer_feedback":
        if (not record.get("consent_ref") or not record.get("brief_ref") or not record.get("participant_ref")
                or record.get("result") not in {"useful","not_useful","mixed","unknown"}
                or not isinstance(record.get("task_version"),str) or not record["task_version"]):
            raise ValueError("consented feedback task/brief/result evidence required")
        a,b=instant(record.get("session_started_at")),instant(record.get("session_ended_at"))
        if not start<=a<b<=end: raise ValueError("feedback session outside reporting window")
        if "quotation" in record or "participant_name" in record or "email" in record:
            raise ValueError("feedback importer retains structured redacted observations, not identity/quotation")
    elif kind=="cost_completeness":
        refs=record.get("cost_refs")
        if not isinstance(refs,list) or len(refs)!=len(set(refs)) or set(record.get("covered_categories",[]))!=CATEGORIES:
            raise ValueError("complete cost categories and unique exact cost references required")
    elif kind=="useful_event_census":
        refs=record.get("assessment_refs")
        if not isinstance(refs,list) or len(refs)!=len(set(refs)):
            raise ValueError("exact nonduplicate useful/negative assessment census required")
    return record


def validate_record(store, receipt_id, *, now, allow_synthetic=False, registry=None, policies=None):
    envelope=get_receipt(store,receipt_id,kind="operating_observation")
    p=_shape(envelope["payload"])
    allowed={"operator_evidence","synthetic"} if allow_synthetic else {"operator_evidence"}
    if p["evidence_kind"] not in allowed:
        raise ValueError("actual operating observation required; templates/assumptions do not measure actuals")
    if p["implementation_hash"]!=implementation_hash():
        raise ValueError("operating implementation changed")
    if not instant(p["observed_at"])<=instant(envelope["observed_at"])<=instant(now):
        raise ValueError("operating observation/import clocks invalid")
    att=validate_attestation(store,p.get("attestation_ref"),purpose="operating_observation",
        subject_hash=digest({k:v for k,v in p.items() if k!="attestation_ref"}),
        bindings={"scope_hash":p["scope_hash"],"implementation_hash":p["implementation_hash"],"policy_hash":p["policy_hash"]},
        now=now,allow_synthetic=allow_synthetic)
    if att["payload"]["evidence_kind"]!=p["evidence_kind"]:
        raise ValueError("operating/attestation evidence kinds differ")
    for ref in _references(p): get_receipt(store,ref)
    if p["kind"] in {"useful_brief","customer_feedback"}:
        if registry is None or policies is None:
            raise ValueError("current registry/policy context required to validate a reviewed brief")
        from .briefs import validate_brief
        # Measure the permissioned use at its evidenced time. Later unrelated
        # cards or ordinary aging do not erase historical operating observations;
        # changed source/review/version state still fails current validation.
        used_at=p["assessed_at"] if p["kind"]=="useful_brief" else p["session_started_at"]
        retained=get_receipt(store,p["brief_ref"],kind="reviewed_brief")
        if instant(retained["observed_at"])>instant(used_at) or instant(retained["payload"]["generated_at"])>instant(used_at):
            raise ValueError("reviewed brief did not exist before the evidenced use/session")
        brief=validate_brief(store,p["brief_ref"],registry,policies,now=used_at,allow_synthetic=allow_synthetic)["payload"]
        if brief.get("scope_hash")!=p["scope_hash"] or brief.get("policy_hash")!=p["policy_hash"] or brief.get("implementation_hash")!=p["implementation_hash"]:
            raise ValueError("operating brief scope/version mismatch")
        if p["evidence_kind"]=="operator_evidence" and brief.get("evidence_kind")!="operator_evidence":
            raise ValueError("synthetic brief cannot establish an actual useful brief or customer")
        if p["kind"]=="useful_brief" and not set(p["event_ids"]).issubset({c["event_id"] for c in brief.get("cards",[])}):
            raise ValueError("usefulness event is absent from the reviewed brief")
    if p["kind"]=="customer_feedback":
        consent=get_receipt(store,p["consent_ref"],kind="operator_attestation")["payload"]
        subject={"participant_ref":p["participant_ref"],"task_version":p["task_version"],"brief_ref":p["brief_ref"],
                 "purpose":"structured_feedback_retention"}
        validate_attestation(store,p["consent_ref"],purpose="customer_feedback_consent",subject_hash=digest(subject),
            bindings={"scope_hash":p["scope_hash"],"implementation_hash":p["implementation_hash"],"policy_hash":p["policy_hash"]},
            now=now,allow_synthetic=allow_synthetic)
        if consent["evidence_kind"]!=p["evidence_kind"]: raise ValueError("feedback consent evidence kind mismatch")
        if instant(consent["reviewed_at"])>instant(p["session_started_at"]):
            raise ValueError("consent must precede observed feedback session")
    return envelope


def record_observation(store, record, *, now, allow_synthetic=False, registry=None, policies=None):
    p=dict(record)
    if p.get("kind")=="review_effort" and p.get("evidence_kind") not in {"template","assumption"}:
        derived=(instant(p.get("ended_at"))-instant(p.get("started_at"))).total_seconds()
        if "elapsed_seconds" in p and p["elapsed_seconds"]!=derived: raise ValueError("caller-supplied elapsed time disagrees with clocks")
        p["elapsed_seconds"]=derived
    _shape(p)
    for prior in list_receipts(store,kind="operating_observation"):
        if prior["payload"]["observation_id"]==p["observation_id"]:
            if prior["payload"]!=p: raise ValueError("operating observation ID reused with different content")
            return prior
    with transaction(store):
        envelope=put_receipt(store,"operating_observation",p,observed_at=now,refs=_references(p),manage_transaction=False)
        if p["evidence_kind"] not in {"template","assumption"}:
            validate_record(store,envelope["receipt_id"],now=now,allow_synthetic=allow_synthetic,registry=registry,policies=policies)
    return envelope


def _economics_report(store, *, scope_hash, window_start, window_end, policy_hash, now, allow_synthetic=False, registry=None, policies=None):
    if not scope_hash or not policy_hash or not instant(window_start)<instant(window_end)<=instant(now):
        raise ValueError("closed economics scope/window/version required")
    relevant=[]; excluded=[]; pending=[]
    for envelope in list_receipts(store,kind="operating_observation"):
        p=envelope["payload"]
        if p.get("scope_hash")!=scope_hash: continue
        if (p.get("window_start"),p.get("window_end"))!=(window_start,window_end):
            excluded.append({"receipt_id":envelope["receipt_id"],"reason":"unmatched_window"}); continue
        try:
            validated=validate_record(store,envelope["receipt_id"],now=now,allow_synthetic=allow_synthetic,registry=registry,policies=policies)
            if p["policy_hash"]!=policy_hash: raise ValueError("operating policy changed")
            relevant.append(validated)
        except (ValueError,KeyError) as exc:
            excluded.append({"receipt_id":envelope["receipt_id"],"reason":str(exc),"evidence_kind":p.get("evidence_kind")})
    kinds={kind:[e for e in relevant if e["payload"]["kind"]==kind] for kind in KINDS}
    costs=kinds["cost"]+kinds["run_cost"]
    components={e["receipt_id"]:cost_components(e["payload"]) for e in costs}
    categories={category for row in components.values() for category in row}
    currencies={p["payload"]["currency"] for p in costs}
    evidence_keys=[p["payload"]["external_reference"]["sha256"] for p in costs]
    if len(evidence_keys)!=len(set(evidence_keys)): pending.append("duplicate_underlying_cost_evidence")
    run_ids=[e["payload"]["run_id"] for e in kinds["run_cost"]]
    if len(run_ids)!=len(set(run_ids)): pending.append("duplicate_run_allocation_id")
    if categories!=CATEGORIES: pending.append("cost_categories_incomplete")
    if len(currencies)!=1: pending.append("cost_currency_missing_or_mixed")
    cost_refs=sorted(e["receipt_id"] for e in costs)
    complete=[e for e in kinds["cost_completeness"] if sorted(e["payload"]["cost_refs"])==cost_refs and set(e["payload"]["covered_categories"])==CATEGORIES]
    if len(complete)!=1: pending.append("exact_cost_completeness_receipt_missing_or_ambiguous")
    if any(x.get("evidence_kind")=="operator_evidence" for x in excluded): pending.append("invalid_actual_in_window_records")
    direct=None if pending else sum((value for row in components.values() for value in row.values()),Decimal(0))
    assessment_refs=sorted(e["receipt_id"] for e in kinds["useful_brief"])
    census=[e for e in kinds["useful_event_census"] if sorted(e["payload"]["assessment_refs"])==assessment_refs]
    denominator_pending=[]
    if len(census)!=1: denominator_pending.append("exact_useful_event_census_missing_or_ambiguous")
    units={}; negatives=0; unknowns=0
    for e in kinds["useful_brief"]:
        p=e["payload"]; brief=get_receipt(store,p["brief_ref"],kind="reviewed_brief")["payload"]
        for card in brief.get("cards",[]):
            if card["event_id"] not in p["event_ids"]: continue
            unit=card.get("event_unit_id")
            if not unit: denominator_pending.append("useful_event_origin_unit_missing"); continue
            units.setdefault(unit,set()).add(p["useful"])
    useful_units=[]
    for unit,values in units.items():
        if values=={True}: useful_units.append(unit)
        elif values=={False}: negatives+=1
        else: unknowns+=1; denominator_pending.append("usefulness_unknown_or_contested")
    useful_count=None if denominator_pending else len(useful_units)
    unit_cost=None
    if direct is not None and useful_count is not None and useful_count>0:
        unit_cost=direct/Decimal(useful_count)
    elif useful_count==0:
        denominator_pending.append("zero_useful_events_no_finite_unit_cost")
    effort_keys=[e["payload"]["external_reference"]["sha256"] for e in kinds["review_effort"]]
    effort=None if len(set(effort_keys))!=len(effort_keys) else sum(e["payload"]["elapsed_seconds"] for e in kinds["review_effort"])
    if len(set(effort_keys))!=len(effort_keys): pending.append("duplicate_review_effort_evidence")
    if not kinds["review_effort"]: effort=None
    categories_cost={category: str(sum((row.get(category,Decimal(0)) for row in components.values()),Decimal(0)))
        if category in categories and len(currencies)==1 else None for category in sorted(CATEGORIES)}
    labor_hours=(sum((decimal_amount(e["payload"]["review_minutes"])+decimal_amount(e["payload"]["operator_minutes"])
                     for e in kinds["run_cost"]),Decimal(0))/Decimal(60)
                 if kinds["run_cost"] and not kinds["cost"] and direct is not None else None)
    synthetic=any(e["payload"]["evidence_kind"]=="synthetic" for e in relevant)
    return {"contract":"omni-operating-economics-1","scope_hash":scope_hash,"window_start":window_start,"window_end":window_end,
        "implementation_hash":implementation_hash(),"policy_hash":policy_hash,"generated_at":now,
        "record_refs":[e["receipt_id"] for e in relevant],"cost_completeness_refs":[e["receipt_id"] for e in complete],
        "useful_census_refs":[e["receipt_id"] for e in census],"excluded_records":excluded,
        "currency":next(iter(currencies)) if len(currencies)==1 else None,"category_costs":categories_cost,
        "direct_cost":str(direct) if direct is not None else None,"useful_event_count":useful_count,
        "useful_event_units":sorted(useful_units),"negative_event_count":negatives,"unknown_event_count":unknowns,
        "cost_per_useful_event":str(unit_cost) if unit_cost is not None else None,"review_effort_seconds":effort,
        "allocated_labor_hours":str(labor_hours) if labor_hours is not None else None,
        "feedback_records":len(kinds["customer_feedback"]),"feedback_results":{value:sum(e["payload"]["result"]==value for e in kinds["customer_feedback"])
            for value in ("useful","not_useful","mixed","unknown")},
        "pending_reasons":sorted(set(pending+denominator_pending)),"evidence_kind":"synthetic" if synthetic else "operator_evidence" if relevant else "none",
        "measured_actuals":bool(costs or kinds["review_effort"] or kinds["useful_brief"] or kinds["customer_feedback"]) and not synthetic,"automatic_activation":False,
        "human_review_status":"pending","authentication":"records_validated_not_humans_invoices_or_customers",
        "workbook_alignment":"closed window; five direct cost categories; exact completeness; unique useful reviewed events; no finite unit cost at zero"}


def economics_report(store, **kwargs):
    with localcontext() as context:
        context.prec=40
        return _economics_report(store,**kwargs)


def record_economics_report(store, *, now, **kwargs):
    report=economics_report(store,now=now,**kwargs)
    return put_receipt(store,"operating_economics",report,observed_at=now,refs=report["record_refs"])
